/**
 * ELECTRA PLAN — Servicio de Cómputo de Materiales y Presupuesto
 * Genera el listado exhaustivo a partir de componentes, conductores y canalizaciones del proyecto.
 */

import { Project, BOMItem } from '../types/electra';

const DEFAULT_PRICES: Record<string, number> = {
  // Cables (precio por metro en ARS aproximado)
  'cable_cu_1.5': 480,
  'cable_cu_2.5': 750,
  'cable_cu_4.0': 1200,
  'cable_cu_6.0': 1850,
  'cable_cu_10.0': 3100,
  // Cañerías (por metro)
  'cano_corrugado_3_4': 380,
  'cano_corrugado_7_8': 520,
  'cano_pvc_rigido_1': 950,
  // Cajas
  'caja_octogonal': 650,
  'caja_rectangular_10x5': 550,
  'caja_paso_10x10': 1400,
  // Aparamenta y comandos
  'punto_interruptor_simple': 1800,
  'punto_interruptor_doble': 2600,
  'punto_conmutador': 2400,
  'punto_pulsador': 1900,
  'tomacorriente_10a_iram': 2100,
  'tomacorriente_20a_tue': 3400,
  'luminaria_led': 8500,
  // Protecciones y Tableros
  'tablero_gabinete_8_mod': 12000,
  'interruptor_termomagnetico_bipolar': 7200,
  'interruptor_diferencial_30ma': 24500,
  'jabalina_pat_con_tomacable': 16000,
  'caja_inspeccion_pat': 5800,
};

export function generateBOM(project: Project, marginPercent: number = 15): BOMItem[] {
  const items: BOMItem[] = [];
  const overrides = project.bomPriceOverrides || {};

  // 1. Cables según los tramos y circuitos del proyecto
  // Agrupar por sección y tipo de conductor
  const cableLengths: Record<string, number> = {};

  for (const wire of project.wires) {
    const key = `cable_cu_${wire.crossSectionMm2 || 1.5}`;
    const baseLength = wire.lengthMeters || 3;
    // Aplicar margen individual de holgura de curvas, cajas y borneras si está configurado en el cable
    const effectiveSlack = wire.slackPercent !== undefined ? wire.slackPercent : marginPercent;
    const realLength = baseLength * (1 + effectiveSlack / 100);
    cableLengths[key] = (cableLengths[key] || 0) + realLength;
  }

  // Si no hay cables dibujados suficientes pero hay circuitos declarados, estimar por circuito
  for (const circ of project.circuits) {
    const key = `cable_cu_${circ.crossSectionMm2}`;
    const estimate = (circ.lengthMetersEstimate || 15) * 3 * (1 + marginPercent / 100); // 3 conductores: Fase, Neutro, Tierra
    if (!cableLengths[key]) {
      cableLengths[key] = estimate;
    }
  }

  // Agregar ítems de cables
  for (const [key, len] of Object.entries(cableLengths)) {
    const gauge = key.replace('cable_cu_', '');
    const roundedMeters = Math.ceil(len);
    const unitPrice = overrides[key] !== undefined ? overrides[key] : (DEFAULT_PRICES[key] || 600);
    items.push({
      id: `bom_${key}`,
      category: 'Conductores Eléctricos',
      name: `Cable Unipolar Cobre IRAM NM 247-3 ${gauge} mm²`,
      description: `Conductor de cobre electrolítico normalizado con aislación PVC para tensión 450/750V (incluye holgura reglamentaria para borneras y curvas).`,
      quantity: roundedMeters,
      unit: 'm',
      unitPrice,
      subtotal: roundedMeters * unitPrice,
      autoGenerated: true,
    });
  }

  // 2. Cañerías / Canalizaciones (Conforme a ocupación <= 35% AEA 771.12)
  const totalConductorMeters = Object.values(cableLengths).reduce((a, b) => a + b, 0);
  const conduitMeters = Math.ceil((totalConductorMeters / 3) * 1.15);
  const conduitPrice = overrides['cano_corrugado_3_4'] !== undefined ? overrides['cano_corrugado_3_4'] : DEFAULT_PRICES['cano_corrugado_3_4'];
  items.push({
    id: 'bom_conduit',
    category: 'Canalizaciones',
    name: 'Caño Corrugado Blanco Ignífugo Ø 3/4" (19 mm) IRAM 62386',
    description: 'Cañería flexible de PVC antillama normalizada para embutir en mampostería y losas (ocupación máxima 35%).',
    quantity: conduitMeters,
    unit: 'm',
    unitPrice: conduitPrice,
    subtotal: conduitMeters * conduitPrice,
    autoGenerated: true,
  });

  // 3. Cajas Octogonales (para centros de techo y apliques)
  const luminariasCount = project.symbols.filter((s) => s.type === 'luminaria').length;
  if (luminariasCount > 0) {
    const p = overrides['caja_octogonal'] ?? DEFAULT_PRICES['caja_octogonal'];
    items.push({
      id: 'bom_cajas_octogonales',
      category: 'Cajas y Accesorios',
      name: 'Caja Octogonal Chica / Grande Chapa 18 / PVC',
      description: 'Caja para bocas de techo y derivaciones de iluminación.',
      quantity: luminariasCount,
      unit: 'u',
      unitPrice: p,
      subtotal: luminariasCount * p,
      autoGenerated: true,
    });
  }

  // 4. Cajas Rectangulares 10x5 (para llaves y tomas)
  const wallUnitsCount = project.symbols.filter(
    (s) => s.category === 'comando' || s.type === 'tomacorriente' || s.type === 'toma_especial'
  ).length;
  if (wallUnitsCount > 0) {
    const p = overrides['caja_rectangular_10x5'] ?? DEFAULT_PRICES['caja_rectangular_10x5'];
    items.push({
      id: 'bom_cajas_rectangulares',
      category: 'Cajas y Accesorios',
      name: 'Caja Rectangular 10x5 cm (Chapa / PVC)',
      description: 'Caja para embutir bastidores de llaves de luz y módulos de tomacorrientes.',
      quantity: wallUnitsCount,
      unit: 'u',
      unitPrice: p,
      subtotal: wallUnitsCount * p,
      autoGenerated: true,
    });
  }

  // 5. Cajas de Paso
  const cpCount = project.symbols.filter((s) => s.type === 'caja_paso').length;
  if (cpCount > 0) {
    const p = overrides['caja_paso_10x10'] ?? DEFAULT_PRICES['caja_paso_10x10'];
    items.push({
      id: 'bom_cajas_paso',
      category: 'Cajas y Accesorios',
      name: 'Caja de Paso Cuadrada 10x10 cm con Tapa',
      description: 'Caja estanca para empalmes de derivación de circuitos.',
      quantity: cpCount,
      unit: 'u',
      unitPrice: p,
      subtotal: cpCount * p,
      autoGenerated: true,
    });
  }

  // 6. Llaves e Interruptores
  const simpleSwCount = project.symbols.filter((s) => s.type === 'interruptor_simple').length;
  if (simpleSwCount > 0) {
    const p = overrides['punto_interruptor_simple'] ?? DEFAULT_PRICES['punto_interruptor_simple'];
    items.push({
      id: 'bom_sw_simple',
      category: 'Aparamenta de Mando',
      name: 'Conjunto Interruptor Unipolar 1 Punto (Bastidor + Tapa + Módulo)',
      description: 'Tecla 10A 250V IRAM 2006 para control de iluminación.',
      quantity: simpleSwCount,
      unit: 'u',
      unitPrice: p,
      subtotal: simpleSwCount * p,
      autoGenerated: true,
    });
  }

  const conmutadorCount = project.symbols.filter((s) => s.type === 'conmutado').length;
  if (conmutadorCount > 0) {
    const p = overrides['punto_conmutador'] ?? DEFAULT_PRICES['punto_conmutador'];
    items.push({
      id: 'bom_sw_conmutado',
      category: 'Aparamenta de Mando',
      name: 'Módulo Interruptor de Combinación / 2 Vías',
      description: 'Llave conmutada 10A para encendido desde 2 lugares.',
      quantity: conmutadorCount,
      unit: 'u',
      unitPrice: p,
      subtotal: conmutadorCount * p,
      autoGenerated: true,
    });
  }

  // 7. Tomacorrientes 10A y 20A
  const tugCount = project.symbols.filter((s) => s.type === 'tomacorriente').length;
  if (tugCount > 0) {
    const p = overrides['tomacorriente_10a_iram'] ?? DEFAULT_PRICES['tomacorriente_10a_iram'];
    items.push({
      id: 'bom_tug',
      category: 'Tomacorrientes',
      name: 'Tomacorriente Doble 2P+T 10A (IRAM 2071)',
      description: 'Módulo de toma corriente con contacto de puesta a tierra reglamentario.',
      quantity: tugCount,
      unit: 'u',
      unitPrice: p,
      subtotal: tugCount * p,
      autoGenerated: true,
    });
  }

  const tueCount = project.symbols.filter((s) => s.type === 'toma_especial').length;
  if (tueCount > 0) {
    const p = overrides['tomacorriente_20a_tue'] ?? DEFAULT_PRICES['tomacorriente_20a_tue'];
    items.push({
      id: 'bom_tue',
      category: 'Tomacorrientes',
      name: 'Tomacorriente Especial 2P+T 20A (IRAM 2071)',
      description: 'Toma reforzado de espigas gruesas para aire acondicionado y cargas pesadas.',
      quantity: tueCount,
      unit: 'u',
      unitPrice: p,
      subtotal: tueCount * p,
      autoGenerated: true,
    });
  }

  // 8. Luminarias
  if (luminariasCount > 0) {
    const p = overrides['luminaria_led'] ?? DEFAULT_PRICES['luminaria_led'];
    items.push({
      id: 'bom_luminarias',
      category: 'Iluminación',
      name: 'Luminaria / Plafón LED Embutir o Aplicar',
      description: 'Artefacto de iluminación de alta eficiencia con driver integrado.',
      quantity: luminariasCount,
      unit: 'u',
      unitPrice: p,
      subtotal: luminariasCount * p,
      autoGenerated: true,
    });
  }

  // 9. Tablero y Protecciones DIN
  const hasTablero = project.symbols.some((s) => s.type === 'tablero');
  if (hasTablero) {
    const pTablero = overrides['tablero_gabinete_8_mod'] ?? DEFAULT_PRICES['tablero_gabinete_8_mod'];
    items.push({
      id: 'bom_tablero_gabinete',
      category: 'Tablero y Protecciones',
      name: 'Gabinete Tablero Seccional Embutir 8 a 12 Módulos DIN',
      description: 'Caja plástica IP40 con riel DIN y puerta fumé para protecciones.',
      quantity: 1,
      unit: 'u',
      unitPrice: pTablero,
      subtotal: pTablero,
      autoGenerated: true,
    });

    const pDif = overrides['interruptor_diferencial_30ma'] ?? DEFAULT_PRICES['interruptor_diferencial_30ma'];
    items.push({
      id: 'bom_diferencial',
      category: 'Tablero y Protecciones',
      name: 'Interruptor Diferencial Bipolar 2x40A 30mA (IRAM-NM-IEC 61008)',
      description: 'Dispositivo de protección contra corrientes de fuga a tierra para personas.',
      quantity: 1,
      unit: 'u',
      unitPrice: pDif,
      subtotal: pDif,
      autoGenerated: true,
    });

    const piaCount = project.circuits.length || 2;
    const pPia = overrides['interruptor_termomagnetico_bipolar'] ?? DEFAULT_PRICES['interruptor_termomagnetico_bipolar'];
    items.push({
      id: 'bom_pias',
      category: 'Tablero y Protecciones',
      name: 'Interruptores Termomagnéticos Bipolares Curva C (PIAs)',
      description: 'Protección para los circuitos derivados (10A, 16A, 20A según circuito).',
      quantity: piaCount,
      unit: 'u',
      unitPrice: pPia,
      subtotal: piaCount * pPia,
      autoGenerated: true,
    });
  }

  // 10. Puesta a Tierra
  const hasPat = project.symbols.some((s) => s.type === 'puesta_tierra');
  if (hasPat) {
    const pJabalina = overrides['jabalina_pat_con_tomacable'] ?? DEFAULT_PRICES['jabalina_pat_con_tomacable'];
    items.push({
      id: 'bom_jabalina',
      category: 'Puesta a Tierra',
      name: 'Jabalina de Acero-Cobre Ø 5/8" x 1.50 m con Tomacable Bronce',
      description: 'Dispersor normalizado IRAM 2309 con conector tipo grapa.',
      quantity: 1,
      unit: 'u',
      unitPrice: pJabalina,
      subtotal: pJabalina,
      autoGenerated: true,
    });

    const pCajaPat = overrides['caja_inspeccion_pat'] ?? DEFAULT_PRICES['caja_inspeccion_pat'];
    items.push({
      id: 'bom_caja_pat',
      category: 'Puesta a Tierra',
      name: 'Cámara de Inspección de Puesta a Tierra con Tapa',
      description: 'Caja plástica o de hormigón para inspección y medición periódica de PAT.',
      quantity: 1,
      unit: 'u',
      unitPrice: pCajaPat,
      subtotal: pCajaPat,
      autoGenerated: true,
    });
  }

  return items;
}
